const bootSectorsOff = 17 // смещение imm8 "mov al, <секторов>" в bootStub
const bootMaxSectors = 17 // читаем в пределах одной дорожки

// WriteBoot собирает образ диска: [boot sector][программа, дополненная до секторов].
func WriteBoot(code []byte) []byte {
	sectors := (len(code) + 511) / 512
	if sectors > bootMaxSectors {
		panic(fmt.Sprintf("$boot: программа слишком большая (%d байт, максимум %d)", len(code), bootMaxSectors*512))
	}
	stub := append([]byte{}, bootStub...)
	stub[bootSectorsOff] = byte(sectors)
	for len(stub) < 510 {
		stub = append(stub, 0)
	}
	stub = append(stub, 0x55, 0xAA)
	out := append(stub, code...)
	for len(out) < (1+sectors)*512 {
		out = append(out, 0)
	}
	return out
}
